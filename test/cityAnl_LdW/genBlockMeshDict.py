#!/usr/bin/env python3
"""Generate a blockMeshDict sized around the city building geometry.

USAGE:
    python3 genBlockMeshDict.py

REQUIREMENTS:
    Run from the cityAnl_LdW case directory with trimesh installed and
    constant/geometry/LdW.stl already generated. The script writes
    system/blockMeshDict, keeping the city geometry centered in the CFD domain.
"""

from pathlib import Path

import trimesh

mesh = trimesh.load("constant/geometry/LdW.stl")

xmin, ymin, zmin = mesh.bounds[0]
xmax, ymax, zmax = mesh.bounds[1]

Lx = xmax - xmin
Ly = ymax - ymin
H  = zmax - zmin

# CFD domain dimensions
upstream   = 5.0 * H
downstream = 15.0 * H
side       = 5.0 * H
top        = 6.0 * H

x0 = xmin - upstream
x1 = xmax + downstream

y0 = ymin - side
y1 = ymax + side

z0 = 0.0
z1 = top

print("Domain")
print(x0, x1)
print(y0, y1)
print(z0, z1)

nx = 80
ny = 80
nz = 40

Path("system").mkdir(exist_ok=True)

with open("system/blockMeshDict", "w") as f:

    f.write(f"""
FoamFile
{{
    version 2.0;
    format ascii;
    class dictionary;
    object blockMeshDict;
}}

// Generated by genBlockMeshDict.py on 2026-10-25.

convertToMeters 1;

vertices
(
    ({x0} {y0} {z0})
    ({x1} {y0} {z0})
    ({x1} {y1} {z0})
    ({x0} {y1} {z0})

    ({x0} {y0} {z1})
    ({x1} {y0} {z1})
    ({x1} {y1} {z1})
    ({x0} {y1} {z1})
);

blocks
(
    hex (0 1 2 3 4 5 6 7)
    ({nx} {ny} {nz})
    simpleGrading (1 1 1)
);

edges();

boundary
(
    inlet
    {{
        type patch;
        faces ((0 4 7 3));
    }}

    outlet
    {{
        type patch;
        faces ((1 2 6 5));
    }}

    sides
    {{
        type symmetry;
        faces
        (
            (0 1 5 4)
            (3 7 6 2)
        );
    }}

    top
    {{
        type symmetry;
        faces ((4 5 6 7));
    }}

    ground
    {{
        type wall;
        faces ((0 3 2 1));
    }}
);

mergePatchPairs();
""")